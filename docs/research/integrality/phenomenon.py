"""phenomenon.py — ЯВЛЕНИЕ «целочисленность из множества слабых ограничений»
(«3‑точечные прямые всех наклонов»), описанное вне рамок нашей задачи.

Это не код решения, а *спецификация явления*: рамки, в которых оно живёт, его принципы,
как оно ведёт себя в подобных системах, по каким признакам его узнают и в чём его суть.
Модуль исполняемый: в конце — маленькие игрушечные модели, показывающие признаки явления
на синтетических системах (без numpy).  Пара к нему — holes.py (чего нам не хватает) и
deep_research_brief_8_integrality.md (план поиска аналогий).

────────────────────────────────────────────────────────────────────────────────────────
0. РАМКИ (frame)
────────────────────────────────────────────────────────────────────────────────────────
Есть конечное множество кандидатов V и семейство «прямых» — подмножеств ℓ ⊆ V с ёмкостью
cap(ℓ) (у нас cap = 2: «не более двух на прямой»).  Ищется max |S| по S ⊆ V с |S ∩ ℓ| ≤ cap(ℓ)
для всех ℓ.  Это задача упаковки (packing) в гиперграфе ограничений.

Ограничения делятся на два сорта — по *силе* относительно дробной релаксации:
  • СИЛЬНЫЕ (rich): |ℓ| ≥ 5 при cap = 2.  Дробное решение x ≡ const должно быть ≤ 2/|ℓ| < 1/2 на
    них, они «видны» линейному программированию (LP): покрытия/двойственные веса дают
    сертификаты. У нас — строки, столбцы, прямые наклона ±1 (до 8 точек).
  • СЛАБЫЕ (weak): |ℓ| = 3 при cap = 2.  Дробное решение x ≡ 2/3 удовлетворяет их ВСЕ разом.
    Поодиночке каждое такое ограничение почти ничего не стоит; LP их не видит.  У нас —
    3‑точечные прямые всех наклонов (~p·log p штук на 8(p−1) кандидатах).

ЯВЛЕНИЕ: истинный оптимум определяется совместным действием СЛАБЫХ ограничений, а не
сильными; разрыв между LP (со всеми ограничениями) и целочисленным оптимумом — линейный по
размеру системы.  У нас: LP ≈ 3.45(p−1), правда (по всем точным данным) 3(p−1)+O(1),
тривиально 4(p−1).

────────────────────────────────────────────────────────────────────────────────────────
1. ПРИНЦИПЫ (principles) — почему слабые ограничения вместе сильны
────────────────────────────────────────────────────────────────────────────────────────
P1. Дуализм «упаковка ↔ трансверсаль».  Пусть H₃ — 3‑однородный гиперграф троек (тройки
    кандидатов, лежащие на одной прямой; здесь и далее только 3‑точечные прямые).  Множество S
    допустимо ⇔ S независимо в H₃ (не содержит целой тройки) ⇔ V \ S — трансверсаль (hitting
    set) для H₃[…]. Значит max |S| = |V| − τ(H₃ на кандидатах), τ — число трансверсали.  Слабые
    ограничения «сильны вместе» ровно тогда, когда τ велико: тройки *распределены* так, что
    одна удалённая точка убивает мало троек (малые степени/костепени, «расширение»).
P2. Дробная слепота.  τ*(H₃) (дробная трансверсаль) ≤ |V|/3 всегда (вес 1/3 на каждой точке), а
    в наших системах τ ≫ τ*: разрыв целочисленности — суть явления.  Никакая LP‑релаксация ранга
    1 (веса на прямых) и даже «локальные неравенства любого ранга на тех же прямых» его не
    закрывают (проверено: IP(1) = LP(1) − O(1) при p ≤ 59).
P3. Насыщение (supersaturation).  Если |S| превышает порог α, число троек внутри S растёт
    линейно по превышению: T(S) ≥ c·(|S| − α − C).  Это «мягкая» форма явления, обычно доступная
    раньше точной; из неё следует α + O(1) через удаление точек.
P4. Устойчивость/жёсткость (stability/rigidity).  Экстремальные (или почти экстремальные)
    множества имеют алгебраическую структуру (у нас: одна гипербола, семейства 9^s), и
    «смешивание» двух структур даёт лишь O(1).  Явление живёт там, где экстремали алгебраические,
    а конструкция «пересекается» с многими другими только слабыми ограничениями.
P5. Локальность против глобальности.  Сертификаты, видящие явление, — глобальные: спектральные
    (SDP/собственные значения), фурье/аналитические (density increment), полиномиальные
    (slice rank, лемма о касательных Сегре), «алгебры флагов» (SDP над плотностями локальных
    конфигураций), либо структурные (классификация почти‑экстремалей + обмен/паросочетание).
    Локальные сертификаты (LP на прямых) — нет.

────────────────────────────────────────────────────────────────────────────────────────
2. ПОВЕДЕНИЕ В ПОДОБНЫХ СИСТЕМАХ (behaviour) — краткий бестиарий
────────────────────────────────────────────────────────────────────────────────────────
  • Родительская задача «no‑three‑in‑line в [N]²»: тривиально 2N, конструкции 1.5N (HJSW), эвристика
    Гая–Келли (π/√3)N ≈ 1.81N; ничего лучше 2N − o(N)?? не доказано (Green, Problem 72).  То же
    явление в чистом виде: всю трудность несут 3‑точечные прямые всех наклонов; инструментов нет.
  • Дуги в PG(2,q) (никакие 3 не коллинеарны): точный ответ q+1 (q нечётно) — счёт через точку
    (Bose): все прямые через точку дуги содержат ≤ 1 другую точку и *разбивают* остальные точки;
    работает благодаря РЕГУЛЯРНОСТИ (все прямые полные).  Структура экстремалей — теорема Сегре
    (лемма о касательных = полиномиальный метод); обобщение — гипотеза MDS (Ball, 2012).
  • Cap sets в F₃ⁿ / 3‑АП в Z_N (3‑точечные «прямые» = арифметические прогрессии): LP слепо;
    ответы даёт анализ Фурье (Рот, density increment) или полиномиальный метод (Ellenberg–Gijswijt).
    Отличие от нас: там нет плотных структурированных экстремалей (у нас плотность 3/4!).
  • Sidon/B_h‑множества: экстремали алгебраические (Singer, Bose), верхняя оценка √N + N^{1/4}… против
    гипотезы √N + O(1) — та же «прибавка O(1)» не доказана.
  • Sum‑free в Z_p: точный ответ ⌊(p+1)/3⌋ (Cauchy–Davenport/Kneser, структура экстремалей — Vosper):
    аддитивный аргумент, «обмен» элементов, а не LP.
  • Турановские задачи для гиперграфов: экстремали алгебраические, точных ответов почти нет; лучшие
    оценки — алгебры флагов (SDP над локальными плотностями) + устойчивость.
  • Спиновые стёкла/фрустрация: энергия основного состояния = наша T(ε) = E + εᵀCε; нижние оценки —
    спектральные, «фрустрированные циклы» (Toulouse), интерполяция; точно решаемо в планарном случае.
  • Модель вертикальных пар (наша же): T(r) ≥ E + (p−1)λ_min(C) — спектральный сертификат виден,
    его аналитический вход (короткие суммы характеров ниже p^{1/4}) — нет.

────────────────────────────────────────────────────────────────────────────────────────
3. ПРИЗНАКИ (signatures) — как узнать явление в данной системе
────────────────────────────────────────────────────────────────────────────────────────
  S1. Много ограничений размера cap+1 (тройки при cap=2), число ~ |V|·polylog, степени ~ log |V|.
  S2. LP со ВСЕМИ ограничениями ≈ LP только с сильными; x ≡ 2/3 (или 1/2) почти допустимо.
  S3. Малые костепени: пара точек лежит в O(1) тройках; тройки «растянуты» по системе.
  S4. Экстремали алгебраически структурированы; численно «прибавка» над конструкцией не растёт (O(1)).
  S5. Мягкие формы (насыщение) численно верны с большим запасом; спектральные оценки численно
      работают (λ_min ограничено/растёт медленно), но их доказательство упирается в «короткие суммы».
  S6. Локальные сертификаты (покрытия, потенциалы) выходят на плато (у нас 3.45) задолго до правды.

────────────────────────────────────────────────────────────────────────────────────────
4. СУТЬ (essence) — одно предложение
────────────────────────────────────────────────────────────────────────────────────────
Целочисленность здесь — это ГЛОБАЛЬНАЯ ЖЁСТКОСТЬ: множество плотности выше порога не может
одновременно «уклониться» от всех троек, потому что тройки образуют расширяющийся, малокостепенный
гиперграф с алгебраически определёнными независимыми множествами максимального размера; никакая
взвешенная сумма локальных ограничений этого не выражает — нужен сертификат, оперирующий
распределением конфигураций (спектр, Фурье, полиномы, флаги) или структурой экстремалей.
"""
