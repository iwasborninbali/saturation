@dataclass
class Signature:
    """Диагностические признаки явления в конкретной системе (что измерить)."""
    n_weak: int                      # число слабых ограничений
    n_ground: int                    # |V|
    mean_degree: float               # среднее число слабых ограничений через точку
    max_codegree: int                # макс. число слабых ограничений через пару точек
    lp_all_over_lp_strong: float     # LP(все)/LP(сильные) — близко к 1 ⇒ слепота
    gain_over_construction: Sequence[int]  # «прибавка» над алгебраической конструкцией по размерам системы
    def verdict(self) -> str:
        cond = [
            self.n_weak >= self.n_ground,                       # S1
            self.lp_all_over_lp_strong > 0.97,                  # S2
            self.max_codegree <= 8,                             # S3 (малые костепени)
            max(self.gain_over_construction) - min(self.gain_over_construction) <= 3,  # S4 (нет роста)
        ]
        return f"{sum(cond)}/4 признаков явления: " + ("ЯВЛЕНИЕ" if sum(cond) >= 3 else "не характерно")

