class Strength(Enum):
    """Сила ограничения относительно дробной релаксации при ёмкости cap."""
    STRONG = "rich: |ℓ| ≥ 2·cap+1 — видно LP, даёт сертификаты-покрытия"
    WEAK   = "weak: |ℓ| = cap+1 — x ≡ cap/(cap+1) удовлетворяет все сразу; LP слепо"

@dataclass(frozen=True)
class Frame:
    """Рамки явления: кандидаты, ограничения с ёмкостями, что оптимизируем."""
    ground_set: str                       # что такое V
    constraints: str                      # что такое «прямые» ℓ
    capacity: int                         # cap(ℓ)
    objective: str = "max |S|, S ⊆ V, |S ∩ ℓ| ≤ cap для всех ℓ"
    def strength(self, size: int) -> Strength:
        return Strength.WEAK if size == self.capacity + 1 else Strength.STRONG

