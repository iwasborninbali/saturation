def lp_blind_toy(n: int = 30, m: int = 200, seed: int = 0) -> Dict[str, float]:
    """Случайный 3-однородный гиперграф на n вершинах с m тройками: дробная упаковка x ≡ 2/3
    (значение 2n/3) против жадной целочисленной независимости.  Показывает P2 в чистом виде."""
    rnd = random.Random(seed)
    triples = set()
    while len(triples) < m:
        triples.add(frozenset(rnd.sample(range(n), 3)))
    # жадная независимость: добавляем вершины, пока не появится целая тройка
    S: Set[int] = set()
    for v in rnd.sample(range(n), n):
        if all(not (t - {v} <= S) for t in triples if v in t):
            S.add(v)
    return {"fractional_2/3": 2 * n / 3, "greedy_integer": len(S), "gap": 2 * n / 3 - len(S)}

def supersaturation_toy(n: int = 40, m: int = 400, seed: int = 1) -> List[Tuple[int, float]]:
    """Среднее число троек внутри случайного k-подмножества как функция k: рост ~ k³ — «насыщение»
    в самой грубой форме (P3).  В структурированных системах порог сдвинут, рост линейный сверх порога."""
    rnd = random.Random(seed)
    triples = set()
    while len(triples) < m:
        triples.add(frozenset(rnd.sample(range(n), 3)))
    out = []
    for k in range(5, n + 1, 5):
        tot = 0
        for _ in range(200):
            S = set(rnd.sample(range(n), k)); tot += sum(1 for t in triples if t <= S)
        out.append((k, tot / 200))
    return out

def transversal_vs_fractional_toy(n: int = 24, m: int = 60, seed: int = 2) -> Dict[str, float]:
    """τ (точно, перебором) против τ* ≤ n/3 и против |E|/Δ: разрыв — признак P1/P2."""
    rnd = random.Random(seed)
    triples: List[FrozenSet[int]] = []
    while len(triples) < m:
        t = frozenset(rnd.sample(range(n), 3))
        if t not in triples: triples.append(t)
    deg = {v: sum(1 for t in triples if v in t) for v in range(n)}
    Delta = max(deg.values())
    tau = None
    for k in range(0, n + 1):
        for T in itertools.combinations(range(n), k):
            Ts = set(T)
            if all(t & Ts for t in triples):
                tau = k; break
        if tau is not None: break
    return {"tau_exact": tau, "E/Delta": m / Delta, "n/3 (tau* upper bound)": n / 3}

