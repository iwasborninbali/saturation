#!/bin/bash
# verdict19.sh — ЕДИНСТВЕННЫЙ источник вердикта по решающему вопросу A280537 n=7 M=19.
#
# История трёх ошибок, каждая внутри предыдущей:
#  1. Монитор объявил «закрыто 584» при 448 кусках: сложил счётчики двух машин и засчитал
#     убитые прогоны за результаты. Отсюда — считать УНИКАЛЬНЫЕ имена и сверять с манифестом.
#  2. Имена файлов результатов были ЗАШИТЫ, а счёт ушёл писать в другие: три часа инструмент
#     показывал «движения нет», пока 45 решателей работали. Отсюда — искать источники по образцу.
#  3. И главное: инструмент проверял ПОДДЕРЕВО, молча предполагая уровень над ним. В нём стояло
#     TOTAL=448 — а 448 есть разбиение ОДНОГО куска верхнего уровня (case_00000) из шестидесяти
#     четырёх. Закрытие всех 448 не доказывало ничего само по себе. Настоящий открытый фронт
#     оказался 209 узлов, а не 45, и 162 из них несли rc=1 — ОШИБКУ решателя, не таймаут.
#
# Поэтому структура теперь ВЫВОДИТСЯ из имён (verdict_tree.py), а не задаётся числом,
# и охватывает дерево целиком, от корня.
#
#   usage: verdict19.sh
set -u
R="$(cd "$(dirname "$0")/../.." && pwd)"; W=/tmp/verdict19; mkdir -p $W   # НЕ чистим кэш заранее: неудачная выгрузка стёрла бы последнюю удачную

# ФАЙЛЫ ИМЕННО ЭТОГО ВОПРОСА. Брать /tmp/*.txt нельзя: там лежат результаты ДРУГИХ вопросов,
# и выполнимый кусок из прогона M=18 (где 18 точек существуют и это наш свидетель) выглядит
# в общей куче как опровержение M=19.
FILES="/tmp/r7_19.txt /tmp/r7_19rev.txt /tmp/rs7_19.txt /tmp/rss19.txt /tmp/r4_19.txt /tmp/rs4b.txt /tmp/ss_a.txt /tmp/ss_a2.txt /tmp/ss_a3.txt /tmp/ss_b.txt /tmp/need_a_res.txt /tmp/need_a2_res.txt /tmp/need_b_res.txt"

pull () { # host zone project tag
  timeout 180 gcloud compute ssh "$1" --zone="$2" --project="$3" \
    --command="for f in $FILES; do [ -f \"\$f\" ] && grep -h '^case_' \"\$f\"; done" 2>/dev/null > "$W/m19_$4.new"
  if [ -s "$W/m19_$4.new" ]; then mv "$W/m19_$4.new" "$W/m19_$4.txt"; else rm -f "$W/m19_$4.new"; fi
  n=$(grep -c . "$W/m19_$4.txt" 2>/dev/null); n=${n:-0}; n=$(printf '%s' "$n" | head -1)
  echo "  с $1 получено строк: $n"
  if [ "$n" -eq 0 ]; then
    echo "  ОТКАЗ: с $1 не получено НИЧЕГО."
    echo "  Потеря доступа к машине НЕ ЕСТЬ закрытие работы. Без её данных всякий узел, который"
    echo "  она считает, выглядит несуществующим, и фронт схлопывается в ноль — то есть отсутствие"
    echo "  сведений принимает вид завершённости. Вердикт не выдаётся."
    MISSING=1
  fi
}
MISSING=0
pull saturation-solver-2 us-central1-b loyobondar-prod a
pull saturation-solver-3 us-west1-b   eg-multi-domain  b
if [ "$MISSING" -ne 0 ]; then
  echo
  echo "ВЕРДИКТ НЕ ВЫДАН: источники неполны (см. отказы выше). Это НЕ «фронт пуст»."
  exit 3
fi
echo
# Факты, опубликованные в репозиторий обоими решающими. Объединяются ИМЕНА, а не числа.
FACTS=""
# ИСТОЧНИКИ ПЕРЕЧИСЛЯЮТСЯ ЯВНО, А НЕ НАБИРАЮТСЯ ПО ОБРАЗЦУ. Образец захватывает то, что
# появится завтра, и молча. Здесь он захватывал facts_ОТОЗВАНЫ_столкновение_имён.txt — файл,
# чьи 280 имён мы сознательно отозвали, — и засчитывал их как закрытые. Первый решатель в тот
# же час поймал у себя худший случай того же класса: образец logs/*.txt втянул закрытия ЗАДАЧИ
# n=5 о трёх точках на прямой, у которой куски называются так же (case_00000, case_00001...),
# и вердикт перевернулся с «63 из 64» на «закрыто целиком». Направление у обоих ОПАСНОЕ:
# чужие закрытия ДОБАВЛЯЮТСЯ, то есть покрытие завышается.
for f in "$R"/logs/a280537/facts_first_solver.txt "$R"/logs/a280537/facts_second_solver.txt; do
  if [ -f "$f" ]; then FACTS="$FACTS $f"; else echo "ОТКАЗ: источника $f нет — покрытие было бы ЗАНИЖЕНО молча"; exit 3; fi
done
[ -n "$FACTS" ] && echo "  файлы фактов из репозитория:$FACTS"
python3 "$R/slack/gates/verdict_tree.py" 7 3 $W/m19_a.txt $W/m19_b.txt ${FACTS:+--facts $FACTS}
