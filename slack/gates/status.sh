#!/bin/bash
# status.sh — состояние счёта с РАЗЛИЧЕНИЕМ «движения нет» и «смотрю не туда».
#
# Второй солвер три часа читал пять источников из девяти, потому что имена файлов были зашиты в
# инструменте, а живой счёт ушёл писать в другие. Занижение у наблюдателя всегда одностороннее:
# он не выдумывает результаты, он их пропускает. Поэтому «прогресса нет» и «я слеп» из вывода
# неотличимы — если только не показать источники и живых производителей рядом.
#
# Здесь: источники ИЩУТСЯ по образцу, у каждого печатается время изменения, и отдельно
# перечисляются живые процессы, которые могли бы писать. Молчание источника при живом процессе —
# подозрение на слепоту, а не вывод об остановке.
#   usage: status.sh <каталог журналов> <образец> [образец процессов]
set -u
DIR=${1:?каталог}; PAT=${2:?образец файлов}; PROC=${3:-cross_solver|no4_fast|symmetric_search|maximize_witness}
echo "== источники по образцу «$PAT» в $DIR"
found=0
for f in $(ls -1 "$DIR"/$PAT 2>/dev/null); do
  found=$((found+1))
  age=$(( $(date +%s) - $(stat -c %Y "$f") ))
  printf "  %-42s строк %-6s обновлён %s с назад\n" "$(basename "$f")" "$(wc -l < "$f")" "$age"
done
[ $found -eq 0 ] && echo "  НИ ОДНОГО ИСТОЧНИКА не найдено — это подозрение на неверный образец, а не на отсутствие работы"
echo "== живые процессы, которые могли бы писать"
alive=$(ps -eo pid,etimes,args --no-headers | grep -E "$PROC" | grep -v grep | wc -l)
ps -eo pid,etimes,args --no-headers | grep -E "$PROC" | grep -v grep | awk '{printf "  pid %s, %s с, %.52s\n", $1, $2, $3" "$4" "$5}' | head -8
echo "  всего живых: $alive"
if [ $alive -gt 0 ] && [ $found -gt 0 ]; then
  fresh=$(for f in $(ls -1 "$DIR"/$PAT 2>/dev/null); do echo $(( $(date +%s) - $(stat -c %Y "$f") )); done | sort -n | head -1)
  if [ "${fresh:-99999}" -gt 900 ]; then
    echo "  ВНИМАНИЕ: процессы живы, но самый свежий источник молчит ${fresh} с."
    echo "  Вывод «прогресса нет» ЗАПРЕЩЁН, пока не показано, что читаются те файлы, в которые пишут."
  fi
fi
