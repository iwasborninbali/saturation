#!/bin/bash
# dispatch.sh — запуск работы с параллелизмом, который определяют ВОРОТА, а не вызывающий.
#
# Существует потому, что ворота, которые только сообщают, не работают: я вызвал preflight.sh,
# получил «можно до 5 задач» и через минуту запустил 10. Дисциплина, которую можно нарушить, —
# не дисциплина. Здесь число параллельных задач берётся из ворот и подставляется в xargs
# автоматически; задать его вручную нельзя.
#
# Второй долг, из-за которого сюда добавлен DONE: список задач брался ОДИН раз и потом
# рассылался на обе машины. Пока он ехал, часть кусков уже закрывалась — и мы считали их
# заново, а сводки складывали одно и то же дважды. Я назвал этот долг вслух и через час
# повторил ту же ошибку, поэтому теперь он закрыт кодом, а не намерением.
#
#   usage: DONE=<файл-закрытых|none:причина> dispatch.sh <local|машина> <задачи> <результаты> [лимит] [ГБ]
#
# DONE обязателен. Файл закрытых берётся у ИНСТРУМЕНТА ВЕРДИКТА (verdict19.sh --list),
# а не собирается на глаз: список, собранный отдельно, разойдётся с вердиктом ровно тогда,
# когда это опаснее всего.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
T=$1; TASKS=$2; OUT=$3; LIM=${4:-3600}; NEEDGB=${5:-3}

[ -s "$TASKS" ] || { echo "ОТКАЗ: список задач $TASKS пуст или отсутствует"; exit 1; }

# --- вычитание уже закрытого -------------------------------------------------
if [ -z "${DONE:-}" ]; then
  echo "ОТКАЗ: не задан DONE. Либо DONE=<файл закрытых кусков> (получить: verdict19.sh --list),"
  echo "       либо DONE=none:<причина>, и причина попадёт в журнал."
  exit 1
fi
RAW=$(grep -c . "$TASKS")
case "$DONE" in
  none:*) echo "== вычитание закрытого ОТКЛЮЧЕНО, причина: ${DONE#none:}"
          FEED="$TASKS" ;;
  *)      [ -s "$DONE" ] || { echo "ОТКАЗ: файл закрытых '$DONE' пуст или отсутствует"; exit 1; }
          FEED=$(mktemp)
          # сверка по ИМЕНИ файла: список задач может нести пути, список закрытых — имена
          awk 'NR==FNR { if ($0 !~ /^#/ && NF) { n=$1; sub(/.*\//,"",n); d[n]=1 } ; next }
               { n=$1; sub(/.*\//,"",n); if (NF && !(n in d)) print }' "$DONE" "$TASKS" > "$FEED"
          KEPT=$(grep -c . "$FEED")
          echo "== задач в списке $RAW, уже закрыто $(($RAW-$KEPT)), к запуску $KEPT"
          if [ "$KEPT" -eq 0 ]; then
            echo "ОТКАЗ: всё из этого списка уже закрыто — запускать нечего."
            rm -f "$FEED"; exit 1
          fi ;;
esac
TASKS="$FEED"
N=$(grep -c . "$TASKS")

# ворота: они же и решают, сколько можно
INFO=$("$HERE/preflight.sh" "$T" "$NEEDGB" 1) || { echo "$INFO"; echo "ОТКАЗ: ворота не пропустили запуск"; exit 1; }
echo "$INFO"
P=$(echo "$INFO" | sed -n 's/.*можно запускать до \([0-9]*\) .*/\1/p')
[ -z "$P" ] && { echo "ОТКАЗ: не удалось получить допустимый параллелизм из ворот"; exit 1; }
[ "$P" -lt 1 ] && { echo "ОТКАЗ: допустимый параллелизм $P"; exit 1; }

echo "== задач $N, параллелизм задан воротами: $P (вручную не переопределяется)"
if [ "$T" = local ]; then
  ( LIM=$LIM xargs -P "$P" -I{} "$HERE/../../slack/gates/runcase.sh" {} "$OUT" < "$TASKS"; echo ALLDONE >> "$OUT" ) &
  echo "запущено в фоне, результаты в $OUT"
else
  case "$T" in
    saturation-solver-2) Z=us-central1-b; PR=loyobondar-prod ;;
    saturation-solver-3) Z=us-west1-b;    PR=eg-multi-domain ;;
    *) echo "ОТКАЗ: неизвестная машина $T"; exit 1 ;;
  esac
  gcloud compute ssh "$T" --zone="$Z" --project="$PR" --command="setsid nohup bash -c 'LIM=$LIM xargs -P $P -I{} ~/sat/runcase.sh {} $OUT < $TASKS; echo ALLDONE >> $OUT' >/dev/null 2>&1 </dev/null &" 2>/dev/null
  echo "запущено на $T в фоне, результаты в $OUT"
fi
