#!/bin/bash
# killproc.sh — снять свои расчётные процессы, НЕ убив собственную оболочку.
#
# Зачем механизм, а не правило. Правило «не искать процессы по командной строке» записано дважды
# и нарушено ПЯТЬ раз за смену: соблазн `pgrep -f` возникает каждый раз, когда имя бинаря длиннее
# пятнадцати знаков и `pgrep -x` его не видит. Записанный урок не защищает; защищает отказ.
#
# Устройство:
#   1) принимает только ТОЧНОЕ имя процесса (comm), никаких образцов;
#   2) отказывает, если имя длиннее 15 знаков, — потому что comm обрезан ядром и совпадения не будет;
#   3) исключает себя и всех своих предков поимённо, даже если бы они совпали.
#
# usage: killproc.sh <точное_имя> [сигнал]
set -u
name=${1:?нужно точное имя процесса}
sig=${2:-TERM}
if [ ${#name} -gt 15 ]; then
    echo "ОТКАЗ: '$name' длиннее 15 знаков. Ядро обрезает comm, точного совпадения не будет." >&2
    echo "       Переименуйте бинарь короче. Искать по командной строке нельзя: пять раз убило свою оболочку." >&2
    exit 2
fi
case "$name" in
    *[*?\[]* ) echo "ОТКАЗ: '$name' похоже на образец. Принимается только точное имя." >&2; exit 2 ;;
    bash|sh|zsh|python3|node ) echo "ОТКАЗ: '$name' — оболочка или интерпретатор, снимать по имени опасно." >&2; exit 2 ;;
esac
# цепочка предков — их не трогаем ни при каких совпадениях
anc=" $$ "; p=$PPID
while [ "$p" -gt 1 ]; do anc="$anc$p "; p=$(awk '{print $4}' /proc/$p/stat 2>/dev/null || echo 1); done
n=0
for pid in $(pgrep -u "$(id -u)" -x "$name" 2>/dev/null); do
    case "$anc" in *" $pid "*) echo "пропущен $pid — он мой предок" >&2; continue ;; esac
    kill -"$sig" "$pid" 2>/dev/null && n=$((n+1))
done
echo "снято процессов '$name': $n"
