#!/bin/bash
# tally.sh — сводить прогоны ТОЛЬКО по завершённым, иначе отказывать.
#
# Зачем механизм. Моя проверочная строка прочла незакончившуюся долю как достигшую цели и
# напечатала вывод, противоположный истинному; в ту же минуту у второго солвера ожидатель прочёл
# пустые файлы как нули. Обе проверки были написаны против ровно этой ошибки.
#
# Устройство: различает ТРИ состояния, а не два.
#   ГОТОВО   — файл содержит признак завершения
#   ИДЁТ     — файла нет, он пуст, или признака завершения в нём нет
#   ОТКАЗ    — если ИДЁТ хоть один: сводка не печатается вовсе
#
# usage: tally.sh '<признак завершения>' '<образец успеха>' файл...
set -u
done_pat=${1:?нужен признак завершения}; ok_pat=${2:?нужен образец успеха}; shift 2
[ $# -gt 0 ] || { echo "ОТКАЗ: не дано ни одного файла. Инструмент без входа не считает по остатку." >&2; exit 2; }
fin=0; run=0; ok=0; miss=""
for f in "$@"; do
    if [ ! -s "$f" ] || ! grep -q -- "$done_pat" "$f" 2>/dev/null; then
        run=$((run+1)); miss="$miss $(basename "$f")"
    else
        fin=$((fin+1)); grep -q -- "$ok_pat" "$f" && ok=$((ok+1))
    fi
done
if [ "$run" -gt 0 ]; then
    echo "ОТКАЗ: $run из $((fin+run)) ещё не завершены —$miss" >&2
    echo "       Сводка не печатается: 'не знаю' нельзя складывать с 'нет'." >&2
    exit 1
fi
echo "готово $fin из $fin; с признаком успеха: $ok"
