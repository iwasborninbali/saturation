#!/bin/bash
# seal.sh — запечатать своё число до чужого счёта и доказать, что оно не двигалось.
#
# Механизм вместо просьбы «не подглядывай»: значение кладётся в неотслеживаемый файл, в репозиторий
# идёт только хеш. После раскрытия хеш доказывает, что значение не подгонялось.
#
# ЧЕГО ОН НЕ ПОКРЫВАЕТ, и это надо говорить всякий раз: он защищает от подгонки задним числом
# и НЕ защищает от того, что считающий уже знает, каких величин ждать. Полная независимость
# требовала бы третьего, ставящего задачу; у нас его нет.
#
# usage: seal.sh put <метка> <файл-со-значением>   |   seal.sh check <метка> <файл>
set -u
mode=${1:?put|check}; tag=${2:?метка}; f=${3:?файл}
dir=docs/sealed; mkdir -p "$dir"
h=$(sha256sum "$f" | cut -d' ' -f1)
# Печатать надо ПРОЦЕДУРУ, а не число: мы оба запечатали одиночные прогоны, и механизм
# безупречно удостоверил два негодных значения. Хеш доказывает неподвижность, не верность.
case "$mode" in
  put)   [ -e "$dir/$tag.sha256" ] && { echo "ОТКАЗ: $tag уже запечатан, перезапечатать нельзя" >&2; exit 2; }
         if ! grep -qE 'сем[ея]н|семя|ОДНО СЕМЯ|повтор' "$f"; then
             echo "ОТКАЗ: в запечатываемом нет указания на число повторов." >&2
             echo "       Впишите «по N семенам» с разбросом, либо явно «ОДНО СЕМЯ» — и тогда" >&2
             echo "       хеш удостоверит негодность вместе со значением, а не вместо него." >&2
             exit 2; fi
         echo "$h" > "$dir/$tag.sha256"; echo "запечатано $tag: $h" ;;
  check) [ -e "$dir/$tag.sha256" ] || { echo "ОТКАЗ: $tag не запечатан" >&2; exit 2; }
         s=$(cat "$dir/$tag.sha256")
         if [ "$s" = "$h" ]; then echo "ХЕШ СОШЁЛСЯ — значение не двигалось"; else
           echo "ХЕШ НЕ СОШЁЛСЯ: запечатано $s, предъявлено $h" >&2; exit 1; fi ;;
  *) echo "ОТКАЗ: режим put или check" >&2; exit 2 ;;
esac
