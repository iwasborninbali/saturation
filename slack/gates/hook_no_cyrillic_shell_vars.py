#!/usr/bin/env python3
"""ЗАПРЕТ КИРИЛЛИЧЕСКИХ ИМЁН ПЕРЕМЕННЫХ В ОБОЛОЧКЕ.

ПОВОД. bash отвергает кириллические идентификаторы («not a valid identifier»), но делает это
ТИХО в том смысле, что скрипт продолжает работать с пустым значением. Однажды killer.sh
напечатал число убитых и не убил никого. Урок был записан ДВАЖДЫ и нарушен в ТРЕТИЙ раз
через одиннадцать часов. Запись не защищает — защищает отказ.

ЧТО ЛОВИТ. Присваивания, циклы, read и подстановки с кириллическим именем В КОНТЕКСТЕ
ОБОЛОЧКИ. Тела heredoc вырезаются: внутри них может быть python, где кириллические имена
законны и работают.

ЧЕГО НЕ ЛОВИТ. Кириллицу в СТРОКАХ и КОММЕНТАРИЯХ — она там уместна и нужна.
Имена ФУНКЦИЙ bash кириллицей принимает; их гейт тоже пропускает, и это верно.
"""
import json, re, sys

КИР = "А-Яа-яЁё"
ОБРАЗЦЫ = [
    (rf"(?:^|[;&|(]|\bthen\b|\bdo\b|\belse\b)\s*[{КИР}][{КИР}\w]*\s*=", "присваивание"),
    (rf"\bread\b[^\n;|]*\s[{КИР}][{КИР}\w]*", "read"),
    (rf"\bfor\s+[{КИР}][{КИР}\w]*\s+in\b", "for"),
    (rf"\$\{{[{КИР}]", "подстановка ${...}"),
    (rf"\$[{КИР}][{КИР}\w]*", "подстановка $..."),
    (rf"\blocal\s+[{КИР}][{КИР}\w]*", "local"),
]


def очистить(cmd):
    """убрать тела heredoc, комментарии и одинарные кавычки-строки"""
    строки, вне, метка = [], True, None
    for строка in cmd.split("\n"):
        if вне:
            m = re.search(r"<<-?\s*'?\"?([A-Za-z_][A-Za-z0-9_]*)'?\"?", строка)
            без_комм = re.sub(r"(^|\s)#.*$", "", строка)
            без_строк = re.sub(r"'[^']*'", "''", без_комм)
            без_строк = re.sub(r'"[^"$]*"', '""', без_строк)
            строки.append(без_строк)
            if m:
                вне, метка = False, m.group(1)
        elif строка.strip() == метка:
            вне, метка = True, None
    return "\n".join(строки)


def main():
    try:
        d = json.load(sys.stdin)
    except Exception:
        sys.exit(0)
    if d.get("tool_name") != "Bash":
        sys.exit(0)
    cmd = очистить((d.get("tool_input") or {}).get("command", "") or "")
    найдено = []
    for обр, имя in ОБРАЗЦЫ:
        m = re.search(обр, cmd, re.M)
        if m:
            найдено.append(f"{имя}: «{m.group(0).strip()[:40]}»")
    if найдено:
        print(
            "КИРИЛЛИЦА В ИМЕНИ ПЕРЕМЕННОЙ ОБОЛОЧКИ. Найдено: " + "; ".join(найдено) + ".\n"
            "bash отвергает такие идентификаторы, и скрипт продолжает работать с пустым\n"
            "значением — то есть печатает правдоподобное и делает не то. Однажды killer.sh\n"
            "так напечатал число убитых и не убил никого.\n"
            "ЧТО СДЕЛАТЬ: имена переменных оболочки — только ASCII. Кириллица уместна в\n"
            "строках, комментариях и ВНУТРИ heredoc (там она законна, например в python).\n"
            "Имена ФУНКЦИЙ bash кириллицей принимает — их гейт не трогает.",
            file=sys.stderr,
        )
        sys.exit(2)
    sys.exit(0)


main()
