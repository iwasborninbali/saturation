#!/usr/bin/env python3
"""PreToolUse (Bash): `pkill -f` / `killall` по образцу — запрещены.

ПОЧЕМУ. Образец `-f` ищется по ВСЕЙ командной строке, а командная строка удалённой
оболочки содержит команду, которой её позвали. Значит `pkill -f <образец>`, посланный
через `gcloud compute ssh`, совпадает сам с собой и убивает мою же сессию. У меня это
случилось ДВАЖДЫ за сутки. Третий раз произошёл иначе и хуже: образец `kissat -q` совпал
и с решателем, и с обёрткой `timeout`, пара родитель-ребёнок выглядела как два конкурента,
я остановил здоровый прогон и отправил в карантин 1614 верных фактов. Решение было верным,
улика — ничего не стоила.

ЧТО ВМЕСТО. slack/gates/killer.sh: доставляется ФАЙЛОМ (кавычки через ssh — отдельный
источник ожогов), обходит /proc, читает cmdline каждого процесса, ЯВНО исключает свой
собственный pid и родителя, и имеет СПИСОК СОХРАНЯЕМЫХ — то, что убивать нельзя.

exit 0 = пропустить, exit 2 = запретить (stderr показывается модели).
"""
import json, re, sys

# pkill/pgrep -f и killall по образцу. -x (точное имя процесса) РАЗРЕШЁН: он не ищет
# по командной строке и потому не может совпасть с зовущей его оболочкой.
ОПАСНО = re.compile(r"\b(pkill|pgrep)\b[^|;&]*?\s-\w*f\w*\b|\bkillall\b\s+-\w*r")

HEREDOC = re.compile(r"<<-?\s*[\"']?(\w+)[\"']?\s*\n.*?\n\1\b", re.S)


def очистить(cmd):
    """ТЕЛА HEREDOC И КОММЕНТАРИИ — НЕ КОМАНДЫ.

    Первое же срабатывание этих ворот было ЛОЖНОЙ ТРЕВОГОЙ: они запретили коммит, в котором
    запрещённая строка стояла ВНУТРИ текста, объясняющего этот самый запрет. Второе — запретило
    ПОЧИНКУ самих ворот, потому что скрипт правки содержал образец. Детектор тревоги ошибается
    в сторону тревоги — правило, на котором я попался третий раз за сутки, и здесь оно дало
    круговую блокировку: ворота не позволяли себя чинить.

    Ворота, отвергающие рассказ о запрещённом наравне с запрещённым, бесполезны: их отключат
    в тот же день, и вместе с ними уйдёт защита от настоящего случая.
    """
    cmd = HEREDOC.sub(" ", cmd)
    cmd = re.sub(r"(?m)(^|\s)#.*$", " ", cmd)
    return cmd


def main():
    try: payload = json.load(sys.stdin)
    except Exception: return 0
    if payload.get("tool_name") != "Bash": return 0
    cmd = очистить((payload.get("tool_input") or {}).get("command") or "")
    m = ОПАСНО.search(cmd)
    if not m: return 0
    # pgrep -f для СЧЁТА безвреден — он ничего не убивает. Запрещаем только убийство.
    #
    # ПРОВЕРКА НА СЛОВО, А НЕ НА ПОДСТРОКУ. Прежняя редакция искала подстроку "kill" во всей
    # команде — и запретила счётный pgrep из-за переменной с именем n_killed в СОСЕДНЕЙ строке.
    # Это третья ложная тревога этих ворот за час: сначала они запретили коммит, описывающий
    # запрет, потом собственную починку, теперь безобидный счёт. Каждая — из-за того, что
    # ворота смотрели на ТЕКСТ, а не на КОМАНДУ.
    УБИВАЕТ = re.compile(r"\|\s*(xargs\s+)?kill\b|\bkill\s+-\w*\s*\$\(")
    if m.group(0).lstrip().startswith("pgrep") and not УБИВАЕТ.search(cmd):
        return 0
    print(
        "ЗАПРЕЩЕНО: убийство по образцу командной строки (`{}`).\n"
        "Образец -f совпадает с ВСЕЙ командной строкой, включая оболочку, которая его позвала:\n"
        "через `gcloud compute ssh` такая команда убивает твою собственную сессию. Было дважды.\n"
        "И совпадает с обёрткой `timeout` вместе с решателем — пара родитель-ребёнок выглядит\n"
        "как два конкурирующих прогона; так был остановлен здоровый расчёт и отозваны 1614 верных фактов.\n"
        "\n"
        "ВМЕСТО ЭТОГО:\n"
        "  * `pkill -x <имя>` — точное имя процесса, по командной строке не ищет;\n"
        "  * slack/gates/killer.sh — доставить ФАЙЛОМ через scp и запустить: обходит /proc,\n"
        "    исключает свой pid и родителя, имеет список сохраняемых.\n"
        .format(m.group(0).strip()), file=sys.stderr)
    return 2

if __name__ == "__main__":
    sys.exit(main())
