#!/bin/bash
# запечатать.sh — запечатанное предсказание: обещание не смотреть заменяется проверяемым.
#
# ЗАЧЕМ. Наша независимость трижды за смену падала до нуля через переписку, которая её и
# обеспечивает: я пишу напарнику числа, чтобы он знал, зачем считать, — и он считает,
# уже зная мой ответ. Просьба «посчитай прежде, чем смотреть» есть дисциплина, то есть
# ненадёжна ровно как все записанные уроки. Здесь она становится механизмом.
#
# КАК. `seal` кладёт значение в НЕОТСЛЕЖИВАЕМЫЙ файл и публикует в репо только его хеш.
# Напарник считает своё, публикует. Потом `reveal` выкладывает значение и проверяет,
# что хеш сошёлся, — то есть что значение не подгонялось после того, как стало известно чужое.
#
# ЗАПУСК:
#   запечатать.sh seal   <метка> <значение...>   -> печатает хеш, кладёт его в docs/sealed/
#   запечатать.sh reveal <метка>                 -> выкладывает значение и сверяет хеш
#   запечатать.sh check  <метка>                 -> сверяет выложенное с опубликованным хешем

set -u
D="docs/sealed"; mkdir -p "$D"
cmd="${1:-}"; label="${2:-}"
[ -z "$cmd" ] || [ -z "$label" ] && { echo "ЗАПУСК: запечатать.sh seal|reveal|check <метка> [значение]" >&2; exit 3; }
secret="$D/$label.secret"; hashf="$D/$label.sha256"; rev="$D/$label.revealed"

case "$cmd" in
  seal)
    shift 2
    [ "$#" -eq 0 ] && { echo "ОШИБКА: нечего печатать" >&2; exit 3; }
    printf '%s\n' "$*" > "$secret"
    h=$(shasum -a 256 "$secret" | awk '{print $1}')
    printf '%s\n' "$h" > "$hashf"
    echo "ЗАПЕЧАТАНО [$label]: $h"
    echo "  значение лежит в $secret (не отслеживается), хеш в $hashf (в репо)"
    ;;
  reveal)
    [ -s "$secret" ] || { echo "НЕЧЕГО РАСКРЫВАТЬ: $secret пуст или отсутствует" >&2; exit 2; }
    [ -s "$hashf" ]  || { echo "НЕТ ОПУБЛИКОВАННОГО ХЕША: $hashf" >&2; exit 2; }
    h=$(shasum -a 256 "$secret" | awk '{print $1}')
    if [ "$h" != "$(cat "$hashf")" ]; then
      echo "ХЕШ НЕ СОШЁЛСЯ — значение менялось после запечатывания. НЕ РАСКРЫВАЮ." >&2; exit 1
    fi
    cp "$secret" "$rev"
    echo "РАСКРЫТО [$label]: $(cat "$rev")"
    echo "  хеш совпал с опубликованным: $h"
    ;;
  check)
    [ -s "$rev" ] && [ -s "$hashf" ] || { echo "НЕ ЗНАЮ: нет раскрытого или хеша" >&2; exit 2; }
    h=$(shasum -a 256 "$rev" | awk '{print $1}')
    [ "$h" = "$(cat "$hashf")" ] && echo "СХОДИТСЯ [$label]" || { echo "РАСХОЖДЕНИЕ [$label]" >&2; exit 1; }
    ;;
  *) echo "неизвестная команда: $cmd" >&2; exit 3 ;;
esac
