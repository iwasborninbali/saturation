#!/bin/bash
# ablation.sh — абляционный тест кодировки: каждый компонент обязан НА ЧТО-ТО ВЛИЯТЬ.
#
# Идея хозяина, доведённая до исполняемой формы. Принцип «оставить только необходимое» проверяется
# механически: убрать компонент и прогнать калибровочный набор известных ответов.
#
#   ответы изменились  -> компонент нужен, и он ПРОВЕРЕН этим набором;
#   ответы не изменились -> одно из двух, и оба требуют действия:
#       (а) компонент ИЗБЫТОЧЕН — убрать (у нас так вышло с тотализатором: при зафиксированных
#           профилях по трём осям сумма определена ими, и глобальная кардинальность не нужна);
#       (б) компонент НЕ ПРОВЕРЯЕТСЯ этим набором — добавить случай, который его задействует.
#           Это опаснее: компонент может быть сломан, а мы не узнаем. Ровно так у нас месяцами
#           могло бы жить симметрийное отсечение, выбрасывающее орбиты: на малых n ответы те же.
#
# Компонент, который НИ НА ЧТО не влияет ни в одном калибровочном случае, — это либо мёртвый код,
# либо непроверенный код. Третьего не дано.
#
#   usage: ablation.sh   (набор случаев и компонентов зашит ниже — правьте под задачу)
set -u
R="$(cd "$(dirname "$0")/../.." && pwd)"
GEN="$R/slack/targets/plane4_cnf.py"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# калибровочные случаи: n, M, ожидаемый вердикт
CASES="4:10:SAT 4:11:UNSAT 5:13:SAT 5:14:UNSAT"
# компоненты: имя и ключ, которым он ВКЛЮЧАЕТСЯ
COMPS="sym:--sym"

run () {  # run <n> <M> <доп.ключи>  -> SAT|UNSAT|OTHER
  local n=$1 M=$2; shift 2
  python3 "$GEN" "$n" "$M" "$TMP/a.cnf" "$@" >/dev/null 2>&1 || { echo GENFAIL; return; }
  timeout 900 kissat -q "$TMP/a.cnf" >/dev/null 2>&1
  case $? in 10) echo SAT;; 20) echo UNSAT;; *) echo OTHER;; esac
}

echo "== абляция кодировки: каждый компонент обязан менять ответ хотя бы на одном случае"
for comp in $COMPS; do
  name=${comp%%:*}; flag=${comp##*:}
  changed=0; total=0
  echo "-- компонент «$name» (ключ $flag)"
  for c in $CASES; do
    n=${c%%:*}; rest=${c#*:}; M=${rest%%:*}; want=${rest##*:}
    with=$(run "$n" "$M" $flag)
    without=$(run "$n" "$M")
    total=$((total+1))
    mark=" "; [ "$with" != "$without" ] && { changed=$((changed+1)); mark="*"; }
    bad=""; [ "$with" != "$want" ] && bad="  ОТВЕТ НЕВЕРЕН (ожидалось $want)"
    echo "   n=$n M=$M: с ним $with, без него $without $mark$bad"
  done
  if [ "$changed" -eq 0 ]; then
    echo "   ВЕРДИКТ: «$name» не влияет НИ НА ОДИН случай — он либо избыточен, либо НЕ ПРОВЕРЯЕТСЯ."
    echo "            Требуется: убрать его ЛИБО добавить случай, который его задействует."
  else
    echo "   ВЕРДИКТ: «$name» меняет ответ в $changed случаях из $total — компонент нужен и проверен"
  fi
done
