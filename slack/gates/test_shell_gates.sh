#!/bin/bash
# test_shell_gates.sh — испытание СКРИПТОВЫХ ворот на то, чем они оба сломались.
#
# У первого солвера `preflight` был сломан весь день: awk печатал большие счётчики в научной
# нотации, потом обрезал их по 32 битам, занятость выходила `-nan`, ворота запрещали запуск.
# У второго — защита диска отказывала 27 раз при 4.5 ГБ свободных, потому что `df` мерил
# несуществующий путь и `${X:-0}` превратил пустоту в ноль.
#
# ОБЩЕЕ У ОБОИХ: разбор выдал НЕ ЧИСЛО, и подстановка по умолчанию сделала из этого приговор.
# Поэтому здесь проверяется не «правильно ли решение», а «получилось ли ЧИСЛО».
set -u
R="$(cd "$(dirname "$0")/../.." && pwd)"
ok=0; bad=0
num () {  # имя, значение
  case "$2" in
    ''|*[!0-9.]*) echo "  НЕ ЧИСЛО: $1 -> «$2»"; bad=$((bad+1)) ;;
    *)            echo "  число ок: $1 = $2"; ok=$((ok+1)) ;;
  esac
}
echo "скриптовые ворота — выдают ли они ЧИСЛА (а не пустоту, слово или nan):"
OUT=$(bash "$R/slack/gates/preflight.sh" local 1 1 2>&1)
num "preflight: ядер"      "$(echo "$OUT" | sed -n 's/.*ядер \([0-9]*\),.*/\1/p' | head -1)"
num "preflight: загрузка"  "$(echo "$OUT" | sed -n 's/.*загрузка \([0-9.]*\),.*/\1/p' | head -1)"
num "preflight: свободно"  "$(echo "$OUT" | sed -n 's/.*свободно ядер ~\([0-9-]*\),.*/\1/p' | head -1 | tr -d -)"
num "preflight: диск"      "$(echo "$OUT" | sed -n 's/.*диск \([0-9]*\)ГБ.*/\1/p' | head -1)"
D=$(mktemp -d)
num "защита диска: свободно МБ" "$(df -m "$D" 2>/dev/null | tail -1 | awk '{print $4}')"
num "awk: большое число через %.0f" "$(awk 'BEGIN{printf "%.0f", 3530031234}')"
num "awk: большое число через print" "$(awk 'BEGIN{print 3530031234}')"
rmdir "$D" 2>/dev/null
echo
[ "$bad" -eq 0 ] && echo "ИТОГ: все $ok величин — числа." || { echo "ИТОГ: НЕ ЧИСЕЛ $bad из $((ok+bad)) — ворота будут врать."; exit 1; }
