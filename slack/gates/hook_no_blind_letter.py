import hashlib, json, os, re, subprocess, sys, time

КОРЕНЬ = "/Users/iwasborninbali/saturation"
ФАЙЛ = f"{КОРЕНЬ}/docs/correspondence/achim_full.md"
РАСПИСКА = f"{КОРЕНЬ}/docs/correspondence/READ_RECEIPT.json"
СКАЧАТЬ = f"{КОРЕНЬ}/slack/gates/скачать_переписку.py"
СРОК = 30 * 60

ПРИЗНАКИ = (
    r"messages\(\)\s*\.\s*send",
    r"users\(\)\.messages\(\)\.send",
    r"gmail[^\n]{0,40}send",
    r"\bsmtplib\b",
    r"\bsendmail\b",
    r"\bmsmtp\b",
    r"send_test_email",
    r"\bmail\s+-s\b",
)


def очистить(cmd):
    """убрать тела heredoc и комментарии — там текст ПРО отправку, а не отправка"""
    строки, вне, метка = [], True, None
    for строка in cmd.split("\n"):
        if вне:
            m = re.search(r"<<-?\s*'?\"?([A-Za-z_][A-Za-z0-9_]*)'?\"?", строка)
            строки.append(re.sub(r"(^|\s)#.*$", "", строка))
            if m:
                вне, метка = False, m.group(1)
        elif строка.strip() == метка:
            вне, метка = True, None
    return "\n".join(строки)


def main():
    try:
        данные = json.load(sys.stdin)
    except Exception:
        sys.exit(0)
    if данные.get("tool_name") != "Bash":
        sys.exit(0)
    cmd = очистить((данные.get("tool_input") or {}).get("command", "") or "")
    if not any(re.search(p, cmd, re.I) for p in ПРИЗНАКИ):
        sys.exit(0)

    беда = None
    if not os.path.exists(РАСПИСКА):
        беда = "расписки нет вовсе"
    else:
        try:
            r = json.load(open(РАСПИСКА, encoding="utf-8"))
            возраст = time.time() - os.path.getmtime(РАСПИСКА)
            if возраст > СРОК:
                беда = f"расписке {int(возраст//60)} минут, допустимо {СРОК//60}"
            else:
                текущий = hashlib.sha256(open(ФАЙЛ, "rb").read()).hexdigest()
                if текущий != r.get("sha256"):
                    беда = "переписка ИЗМЕНИЛАСЬ с момента расписки — пришло новое письмо"
        except Exception as e:
            беда = f"расписка нечитаема: {e}"

    if беда:
        print(
            f"ОТПРАВКА ПИСЬМА ЗАБЛОКИРОВАНА: {беда}.\n"
            f"Правило хозяина: перед ЛЮБЫМ письмом читается ПОЛНАЯ история переписки.\n"
            f"Дважды за два дня письмо готовилось на неполном знании — один раз с вопросом,\n"
            f"на который уже был ответ, другой раз с чужим числом, поданным как наше.\n\n"
            f"ЧТО СДЕЛАТЬ:\n"
            f"  1) ~/.config/nusadua-studio-agent/venv/bin/python3 {СКАЧАТЬ}\n"
            f"  2) ПРОЧИТАТЬ ЦЕЛИКОМ {ФАЙЛ}\n"
            f"  3) повторить отправку (расписка действует 30 минут)\n",
            file=sys.stderr,
        )
        sys.exit(2)
    sys.exit(0)


main()
