#!/bin/bash
# готово_или_не_знаю.sh — считать ТОЛЬКО по завершённым файлам, иначе сказать «НЕ ЗНАЮ».
#
# ЗАЧЕМ. 2026-08-22, одна минута, две проверки, обе солгали:
#   * мой ожидатель прочёл ПУСТЫЕ файлы при восьми живых процессах и напечатал «0 из 8»
#     — число случайно совпало с истинным, и я бы отправил его как результат;
#   * проверка первого решателя прочла НЕЗАКОНЧИВШУЮСЯ долю как достигшую цели и
#     напечатала «хоть одна достала» при пяти ещё работавших.
# Обе не различали «НЕТ» и «НЕ ЗНАЮ». Молчание файла читалось как ответ.
#
# ПРАВИЛО, КОТОРОЕ ЭТОТ СКРИПТ ДЕЛАЕТ МЕХАНИЧЕСКИМ: всякая проверка обязана различать
# три состояния — НЕ ГОТОВО, ГОТОВО-НЕТ, ГОТОВО-ДА — и при первом ОТКАЗЫВАТЬСЯ отвечать.
#
# ЗАПУСК: готово_или_не_знаю.sh <ожидаемое_число> <признак_завершения> <искомое> <файлы...>
#   <признак_завершения> — строка, которую файл получает ТОЛЬКО дописав до конца
#                          (у наших счётчиков это «ИСЧЕРПАНО» или «ОБОРВАНО»)
#   <искомое>            — что считаем среди завершённых
# КОД ВОЗВРАТА: 0 — ответ дан; 2 — НЕ ЗНАЮ; 3 — ошибка вызова.

set -u
if [ "$#" -lt 4 ]; then echo "ОШИБКА ВЫЗОВА: нужно <N> <признак> <искомое> <файлы...>" >&2; exit 3; fi
want="$1"; done_mark="$2"; needle="$3"; shift 3

total=0; finished=0; hits=0; missing=""
for f in "$@"; do
  total=$((total+1))
  if [ ! -s "$f" ]; then missing="$missing $f(пуст)"; continue; fi
  if ! grep -q -- "$done_mark" "$f"; then missing="$missing $f(без признака)"; continue; fi
  finished=$((finished+1))
  grep -q -- "$needle" "$f" && hits=$((hits+1))
done

if [ "$total" -ne "$want" ]; then
  echo "НЕ ЗНАЮ: файлов $total, ожидалось $want"; exit 2
fi
if [ "$finished" -ne "$want" ]; then
  echo "НЕ ЗНАЮ: завершено $finished из $want;  не готовы:$missing"; exit 2
fi
echo "ГОТОВО: ${hits} из ${want} содержат: ${needle}"
exit 0
