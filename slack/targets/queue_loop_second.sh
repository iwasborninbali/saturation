#!/bin/bash
# queue_loop.sh — самопополняющаяся очередь.
#
# ЗАЧЕМ. Очередь конечна: когда список кусков кончается, xargs выходит и машина замолкает.
# Ночью это означает, что 32 ядра стоят до утра. Фронт ПЕРЕСЧИТЫВАЕТСЯ из фактов, а не
# назначается однажды: открытый кусок = ребёнок разбитого узла, у которого нет ни собственного
# закрытия, ни своих детей. Это тот же долг, что я назвал раньше — список задач должен браться
# из вердикта, а не из файла, написанного руками.
#
# ОСТАНОВКА ЧЕСТНАЯ: если фронт пуст, цикл выходит и ГОВОРИТ об этом, а не крутится вхолостую.
set -u
FACTS="${SN_FACTS:-/tmp/facts_vm.txt}"
REPO="${SN_REPO:-/home/iwasborninbali/sat}"
PAR="${QL_PAR:-$(( $(nproc) - 2 ))}"
LIM="${QL_LIM:-120}"
round=0
while :; do
  round=$((round+1))
  rm -f /tmp/frontier.txt
  # ФРОНТ СЧИТАЕТСЯ ИЗ ОБЪЕДИНЕНИЯ, А НЕ ИЗ СВОИХ ФАКТОВ. Считая только по своим, машина
  # переделывает то, что коллега уже закрыл: у меня было открыто 36 кусков глубины 3,
  # в объединении закрытых. Мера продвижения показала это сразу — вклад глубины 3 исчез,
  # как только я подмешал чужие факты. Объединять ИМЕНА можно (идемпотентно), числа нельзя.
  python3 "$REPO/frontier_second.py" "$FACTS" ${MERGED:-/tmp/facts_merged.txt} > /tmp/frontier_round.txt 2>&1
  Q="/tmp/frontier_$round.txt"
  # ТРИ ИСХОДА, а не два: пересчёт мог НЕ СОСТОЯТЬСЯ, и это не то же самое, что пустой фронт.
  if [ ! -f /tmp/frontier.txt ]; then
    echo "ОТКАЗ круга $round: пересчёт фронта не состоялся — это отказ ИЗМЕРЕНИЯ, не пустой фронт"
    sed -n '1,5p' /tmp/frontier_round.txt
    exit 4
  fi
  cp /tmp/frontier.txt "$Q"
  N=$(wc -l < "$Q" 2>/dev/null || echo 0)
  echo "=== круг $round: во фронте $N кусков ($(date -u +%H:%M:%S)) ==="
  if [ "$N" -eq 0 ]; then
    echo "ФРОНТ ПУСТ — считать нечего. Это либо победа, либо ошибка пересчёта; проверь вердиктом."
    exit 0
  fi
  xargs -a "$Q" -P "$PAR" -I{} "$REPO/sos_named_second.sh" {} "$LIM"
  echo "=== круг $round завершён; фактов: $(wc -l < "$FACTS") ==="
done
