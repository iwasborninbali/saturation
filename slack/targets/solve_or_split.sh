#!/bin/bash
# solve_or_split.sh — рекурсивный проход: короткий срок решателю, уцелевших сразу дробим.
#
# Двумодальность измерена: кусок либо умирает даром (распространением), либо не даётся вовсе.
# Значит долгий лимит — чистая потеря: он не помогает трудным и не нужен лёгким.
#
# РАСПИСАНИЕ СТОЛБЦОВ. Каждый следующий столбец ВНУТРИ слоя множит число выживших на 7.34, 3.32,
# 2.36, 1.95, 1.73, 1.59; первый столбец СВЕЖЕГО слоя — всегда на 64. Поэтому слой исчерпывается
# целиком, и только потом берётся следующий: даже последний столбец слоя вчетверо десятков раз
# дешевле первого столбца нового.
#
# ПОРЯДОК ОБХОДА обратный: высокие индексы — тройки, они при занятой ёмкости слоя невыполнимы
# даром; низкие — выжившие. Прямой порядок ставит трудные первыми и до дармовых не доходит.
#
#   solve_or_split.sh <cnf> <индекс-столбца-в-расписании> <лимит-с> <макс-глубина>
SP=/tmp/claude-1000/-home-pmbot-projects-solver-kit/df30d6f4-57eb-4267-abb8-3e2d3cd04a69/scratchpad
R=/home/pmbot/projects/saturation_peer
f="$1"; ci="$2"; lim="$3"; maxd="$4"
# ВСЕ 49 столбцов. Прежде здесь было четырнадцать, и рекурсия упиралась в конец расписания,
# печатая «ПРЕДЕЛ» и оставляя узел незакрытым НАВСЕГДА — то есть тупик, а не медленность.
# Столбцов в кубе 7x7 = 49, и дробить можно по любому: ёмкость столбца 3 исчерпывает его при
# любом выборе. Порядок — послойный, как измерено: слой исчерпывается целиком, потом следующий.
SCHED=($(seq 0 48))
b=$(basename "$f" .cnf)
# ПРОПУСК УЖЕ ИЗВЕСТНОГО. Перезапуск прохода не должен перерешать закрытое: факты — это измерения,
# и повторять их незачем. Пропуск идёт по ТОЧНОМУ имени из опубликованного файла фактов; если файла
# нет, ничего не пропускается (отсутствие сведений не есть разрешение считать закрытым).
FACTS=${FACTS:-$R/logs/a280537/facts_first_solver.txt}
if [ -f "$FACTS" ] && grep -qxF "$b" "$FACTS" 2>/dev/null; then echo "ЗАКРЫТ $b"; exit 0; fi

# ПРЕДСКАЗАНИЕ ТРУДНОСТИ ПО ИМЕНИ. Кусок труден ровно тогда, когда его зафиксированные столбцы
# взяли меньше точек, чем причитается по средней плотности, и остаток обязан быть плотнее целого.
# Измерено на 21757 закрытиях и 395 дроблениях: ниже 0.35 не раздробился НИ ОДИН кусок, выше —
# от 14 до 64 процентов, и порог держится внутри каждой глубины отдельно
# (docs/research/hardness_threshold.md). Размер подмножества по индексу: 0 -> 0, 1..7 -> 1,
# 8..28 -> 2, 29..63 -> 3. Значит плотность считается арифметикой, без решателя и без файла.
# Дробить сразу — всегда состоятельно: разбиение исчерпывающе независимо от того, почему мы его
# выбрали. Экономия — срок решателя (120 с) на каждом таком куске.
# ЗАЩИТА ОТ ПЕРЕНОСА. Порог измерен для A280537 при n=7, M=19 и НИ ДЛЯ ЧЕГО ДРУГОГО. Числа 19 и 49
# зашиты в счёте плотности ниже; если задача другая, предсказатель обязан ОТКЛЮЧИТЬСЯ, а не выдать
# правдоподобное число не для той задачи. Молча перенесённая калибровка — ровно тот вид ошибки,
# который мы весь день ловили: величина, честная в одном месте и лживая в другом.
PROBLEM=${PROBLEM:-a280537_n7_M19}
THRESH=${THRESH:-0.375}
if [ "$PROBLEM" != "a280537_n7_M19" ]; then
    THRESH=99            # заведомо недостижимо: предсказатель выключен
fi
dens=$(echo "$b" | awk -v M=19 -v NC=49 '{
    n=split($0, a, "_s"); pts=0; k=0
    for (i=2; i<=n; i++) { j=a[i]+0; k++
        if (j==0) sz=0; else if (j<=7) sz=1; else if (j<=28) sz=2; else sz=3
        pts+=sz }
    rc=NC-k; if (rc<=0) { print 0; exit }
    printf "%.4f", (M-pts)/rc }')
if awk -v d="$dens" -v t="$THRESH" 'BEGIN{exit !(d>t)}' && [ "$ci" -lt "$maxd" ]; then
    echo "ТРУДЕН ПО ПЛОТНОСТИ $b (d=$dens) — дроблю без решателя"
    rc=124
else
    timeout "$lim" ~/bin/kissat -q "$f" >/dev/null 2>&1; rc=$?
fi
case $rc in
  20) echo "ЗАКРЫТ $b"; exit 0 ;;
  10) echo "ВЫПОЛНИМ $b — ЗАЯВЛЕНИЕ РУШИТСЯ"; cp "$f" $SP/SAT_$b.cnf; exit 9 ;;
esac
if [ "$ci" -ge "$maxd" ] || [ "$ci" -ge "${#SCHED[@]}" ]; then
  echo "ПРЕДЕЛ $b (расписание исчерпано на шаге $ci)"; exit 1
fi
col=${SCHED[$ci]}
d=$SP/sos/$b; rm -rf $d; mkdir -p $d
python3 $R/slack/targets/subsplit.py "$f" 7 "$col" 3 $d >/dev/null 2>&1
k=$(ls $d/*.cnf 2>/dev/null | wc -l)
if [ "$k" -ne 64 ]; then echo "ОТКАЗ $b: детей $k вместо 64"; rm -rf $d; exit 2; fi
echo "ДРОБЛЮ $b столбцом $col"
bad=0
for g in $(ls -r $d/*.cnf); do
  $R/slack/targets/solve_or_split.sh "$g" $((ci+1)) "$lim" "$maxd" || bad=1
  rm -f "$g"
done
rm -rf $d
[ $bad -eq 0 ] && echo "ЗАКРЫТ ЧЕРЕЗ ПРОДОЛЖЕНИЯ $b" || echo "НЕ ЗАКРЫТ $b"
exit $bad
