/* brute_n3.c — ПОЛНЫЙ перебор всех C(27,8) подмножеств без единого отсечения.
 *
 * Зачем. Число максимумов при n=3 (16 штук) посчитано моим же обходом с ёмкостным отсечением,
 * с порядком по индексу и с проверкой «слой не более трёх». Всё это — одно понимание задачи.
 * Если оно неверно, отсечение закрепит ошибку и обход будет выглядеть исправным.
 *
 * Здесь нет отсечений вовсе: перебираются ВСЕ 2 220 075 подмножеств по восемь клеток, и каждое
 * проверяется полным счётом всех C(8,3)=56 троек и C(8,4)=70 четвёрок. Медленно и глупо —
 * и потому не разделяет с обходом ни одной догадки, кроме самого определения запрета.
 */
#include <stdio.h>
static int X[27],Y[27],Z[27];
int main(void){
    int m=0; for(int x=0;x<3;x++)for(int y=0;y<3;y++)for(int z=0;z<3;z++){X[m]=x;Y[m]=y;Z[m]=z;m++;}
    long long total=0, valid=0;
    int c[8];
    for(c[0]=0;c[0]<27;c[0]++)for(c[1]=c[0]+1;c[1]<27;c[1]++)for(c[2]=c[1]+1;c[2]<27;c[2]++)
    for(c[3]=c[2]+1;c[3]<27;c[3]++)for(c[4]=c[3]+1;c[4]<27;c[4]++)for(c[5]=c[4]+1;c[5]<27;c[5]++)
    for(c[6]=c[5]+1;c[6]<27;c[6]++)for(c[7]=c[6]+1;c[7]<27;c[7]++){
        total++;
        int bad=0;
        for(int a=0;a<8&&!bad;a++)for(int b=a+1;b<8&&!bad;b++)for(int d=b+1;d<8&&!bad;d++){
            long long ux=X[c[b]]-X[c[a]],uy=Y[c[b]]-Y[c[a]],uz=Z[c[b]]-Z[c[a]];
            long long vx=X[c[d]]-X[c[a]],vy=Y[c[d]]-Y[c[a]],vz=Z[c[d]]-Z[c[a]];
            if((uy*vz-uz*vy)==0&&(uz*vx-ux*vz)==0&&(ux*vy-uy*vx)==0){bad=1;break;}
            for(int e=d+1;e<8;e++){
                long long wx=X[c[e]]-X[c[a]],wy=Y[c[e]]-Y[c[a]],wz=Z[c[e]]-Z[c[a]];
                if(ux*(vy*wz-vz*wy)-uy*(vx*wz-vz*wx)+uz*(vx*wy-vy*wx)==0){bad=1;break;}
            }
        }
        if(!bad) valid++;
    }
    printf("n=3, M=8: перебрано ВСЕХ подмножеств %lld, правильных %lld\n", total, valid);
    printf("(мой обход с отсечениями давал 16)\n");
    return 0;
}
