"""midpoint_obstruction.py — ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ: механизм, объясняющий, почему при n=5 крайние слои не могут нести 2n.

Наблюдение из проверенных свидетелей: оптимум имеет одинаковый профиль по всем трём осям, крайние
слои несут 2n точек, внутренние 2n-2 — при n = 2, 3, 4 и (по нашему свидетелю) 6.  При n = 5 профиль
оптимума 8,8,8,8,8: НИ ОДИН слой не достигает 2n = 10.

Гипотеза о причине. Пусть слои x = 0 и x = n-1 несут по 2n точек. Если n-1 ЧЁТНО, середина отрезка
между точкой первого слоя и точкой последнего лежит в слое x = (n-1)/2 — на решётке, — и обязана быть
пустой, иначе три точки коллинеарны. Число таких запретов растёт как (2n)^2/4 = n^2, а в слое всего
n^2 клеток. При n = 5: 100 пар, у четверти обе координатные суммы чётны, то есть до 25 запретов на
25 клеток. При n = 6 расстояние между крайними слоями равно 5 — нечётно, середины на решётку не
попадают, запрета нет вовсе.

ИТОГ ПРОВЕРКИ: гипотеза НЕВЕРНА. Точный счёт (n=5, все 32 конфигурации из 10 точек в сетке 5x5)
даёт: при 2n точках в обоих крайних слоях в среднем слое остаётся от 6 до 16 свободных клеток,
максимум 16. Но планарный потолок среднего слоя и так равен 2n = 10 < 16, поэтому запрет серединами
НЕ СВЯЗЫВАЕТ и профиль 10,8,8,8,10 этим механизмом не исключается. Грубая оценка такого профиля
даёт 52 — выше искомых 44, то есть ничего не доказывает.

Механизм, объясняющий провал n=5, остаётся НЕИЗВЕСТНЫМ. Скрипт сохранён именно как отрицательный
результат: он закрывает простое объяснение, которое иначе пришлось бы придумывать заново.

Скрипт считает это точно: перебирает ВСЕ двумерные конфигурации из 2n точек без трёх коллинеарных
в сетке n x n (с точностью до ничего — все помеченные), и для каждой пары (верхний слой, нижний слой)
считает, сколько клеток среднего слоя остаётся свободными.
"""
import sys
from itertools import combinations

def planar_max_sets(n, size):
    """все помеченные конфигурации из `size` точек в сетке n x n без трёх коллинеарных"""
    cells = [(x, y) for x in range(n) for y in range(n)]
    idx = {c: i for i, c in enumerate(cells)}
    # прямые с >= 3 точками
    lines = {}
    for a, b in combinations(cells, 2):
        d = (b[0]-a[0], b[1]-a[1])
        from math import gcd
        g = gcd(abs(d[0]), abs(d[1])); d = (d[0]//g, d[1]//g)
        if d < (0, 0): d = (-d[0], -d[1])
        p = a
        while True:
            q = (p[0]-d[0], p[1]-d[1])
            if all(0 <= t < n for t in q): p = q
            else: break
        lines.setdefault((p, d), None)
    L = []
    for (p, d) in lines:
        m, q = [], p
        while all(0 <= t < n for t in q): m.append(idx[q]); q = (q[0]+d[0], q[1]+d[1])
        if len(m) >= 3: L.append(m)
    inc = [[] for _ in cells]
    for li, m in enumerate(L):
        for i in m: inc[i].append(li)
    out, cnt = [], [0]*len(L)
    sel = []
    def rec(start):
        if len(sel) == size: out.append(tuple(sel)); return
        if len(cells) - start < size - len(sel): return
        for i in range(start, len(cells)):
            if any(cnt[li] >= 2 for li in inc[i]): continue
            for li in inc[i]: cnt[li] += 1
            sel.append(i); rec(i+1); sel.pop()
            for li in inc[i]: cnt[li] -= 1
    rec(0)
    return cells, out

def main(n):
    size = 2*n
    cells, sets = planar_max_sets(n, size)
    print(f"n={n}: конфигураций из {size} точек в сетке {n}x{n} без трёх коллинеарных: {len(sets)}")
    if (n-1) % 2:
        print(f"  расстояние между крайними слоями {n-1} НЕЧЁТНО — середины на решётку не попадают, механизм не работает")
        return
    mid = (n-1)//2
    best, worst = -1, 10**9
    for A in sets:
        pa = [cells[i] for i in A]
        for B in sets:
            pb = [cells[i] for i in B]
            forb = set()
            for u in pa:
                for v in pb:
                    if (u[0]+v[0]) % 2 == 0 and (u[1]+v[1]) % 2 == 0:
                        forb.add(((u[0]+v[0])//2, (u[1]+v[1])//2))
            free = n*n - len(forb)
            best = max(best, free); worst = min(worst, free)
    print(f"  крайние слои по {size} точек; в среднем слое x={mid} свободных клеток:")
    print(f"    максимум по всем парам {best}, минимум {worst}  (в слое всего {n*n})")
    print(f"  => при 2n в обоих крайних слоях средний слой несёт не более {best} точек")
    tot = 2*size + best + (n-3)*(2*n-2)
    print(f"  грубая верхняя оценка такого профиля: 2*{size} + {best} + {n-3}*{2*n-2} = {tot}")

if __name__ == "__main__":
    for n in (int(a) for a in (sys.argv[1:] or ["4", "5"])): main(n)
