#!/bin/bash
# sos_second.sh — рекурсивный проход второго солвера: короткий срок решателю, уцелевших дробим.
# Основан на solve_or_split.sh первого солвера; пути под мои машины, плюс запись ФАКТОВ.
#
# Почему так, а не иначе — всё измерено сегодня:
#  * двумодальность: кусок либо умирает даром, либо не даётся вовсе -> длинный лимит бесполезен
#    по обоим краям (трудным не помогает, лёгким не нужен);
#  * расписание столбцов: внутри слоя множитель 7.34, 3.32, 2.36, 1.95, 1.73, 1.59, а первый
#    столбец свежего слоя — 64; поэтому слой исчерпывается ЦЕЛИКОМ;
#  * обратный порядок обхода: высокие индексы (тройки) при занятой ёмкости слоя невыполнимы
#    даром, прямой порядок ставит трудные первыми;
#  * имя временного файла НЕСЁТ базу: иначе подкуски разных баз пишутся в один путь.
#
#   sos_second.sh <cnf> <шаг-расписания> <лимит-с> <макс-шагов> <файл-фактов> [n]
# n по умолчанию 7; для n=6 расписание короче (слой 6 столбцов).
set -u
W=${SOS_WORK:-/tmp/sos}
R=${SOS_REPO:-$HOME/sat}
f="$1"; ci="$2"; lim="$3"; maxd="$4"; facts="$5"; NN="${6:-7}"
# Расписание: слой x=0 целиком, затем x=1. Длина слоя = n столбцов.
# СТОЛБЦОВ В КУБЕ n*n = 49 ПРИ n=7, а не 2n. Прежний список из 14 записей давал НАСТОЯЩИЙ
# ТУПИК: дойдя до конца, рекурсия печатала «предел» и оставляла узел незакрытым НАВСЕГДА —
# дробить дальше было нечем. У меня таких 238, у первого солвера 12 631. Ложных фактов это
# не породило (тупик факта не пишет), но ветки гасило молча, и застой закрытий объяснялся
# этим, а не трудностью задачи. Опять свойство оснастки, выданное за свойство задачи.
SCHED=(); for ((c=0;c<NN*NN;c++)); do SCHED+=($c); done
b=$(basename "$f" .cnf)

# ПЛОТНОСТЬ ОСТАТКА — трудность, вычислимая ИЗ ИМЕНИ до запуска решателя.
# d = (M - p)/(49 - k). Ниже 0.35 не раздробился ни один кусок из 4704 (замерено дважды,
# независимо, на разных машинах). Порог «дробить сразу» — ДРУГОЙ (0.38): при 0.37 дробится
# лишь 16%, и пропуск решателя теряет 13.6 с на кусок вместо экономии.
#
# ПОРОГ БЕРЁТСЯ ИЗ ВОРОТ, А НЕ ИЗ ЭТОГО ФАЙЛА. Число, записанное в скрипте, живёт своей жизнью
# и переносится на другие n и M незаметно — ровно та ошибка, которую мы ловили весь день до
# этого. Ворота отказывают, если для данной задачи замера нет, и тогда мы просто решаем всё
# как раньше: пропуск оптимизации безопасен, применение неизмеренного порога — нет.
if [ -z "${SOS_DENS:-}" ]; then
  SOS_DENS=$(python3 -c "
import sys, os
# Путь к воротам: рядом со скриптом (репозиторий) либо там, куда их положили на машине.
for c in (os.path.join(os.path.dirname('$0'), '..', 'gates'), os.path.expanduser('~/sat/gates'), os.path.expanduser('~/gates')):
    if os.path.exists(os.path.join(c, 'gates.py')): sys.path.insert(0, c); break
try:
    from gates import gate_density_threshold as g
    print(g('a280537', $NN, 19))
except Exception as e:
    print('НЕТ')
" 2>/dev/null) || SOS_DENS=НЕТ
  export SOS_DENS
  [ "$SOS_DENS" = "НЕТ" ] && echo "ВОРОТА: порога плотности для n=$NN нет — решаю всё без пропуска (это безопасно, но медленнее)"
fi

rc=""
if [ "$SOS_DENS" != "НЕТ" ] && [ -n "$SOS_DENS" ]; then
  DENS=$(python3 - "$b" <<'PYD'
import sys
from itertools import combinations
N,M,COLS=7,19,49
S=[x for k in range(4) for x in combinations(range(N),k)]
idxs=[int(t) for t in sys.argv[1].split("_s")[1:]]
p=sum(len(S[i]) for i in idxs); k=len(idxs)+1
print(f"{(M-p)/(COLS-k):.4f}")
PYD
)
  # ВЕРХНЯЯ ГРАНИЦА. Столбцы обходятся послойно: оставшиеся rc столбцов покрывают около rc/7
  # слоёв, слой держит 3 точки, значит выполнимый кусок имеет d <= 3/7 = 0.4286. Выше — кусок
  # невыполним по чистому счёту, и решатель закрывает его распространением, не начиная поиска.
  # У цепочки пустых подмножеств p=0, поэтому d = 19/(49-k) РАСТЁТ с глубиной: 0.45 на седьмом
  # столбце, 1.0 на тридцатом, 19 на сорок восьмом. Без потолка предсказатель звал такой кусок
  # трудным на каждом шаге и дробил до самого дна расписания вместо мгновенного закрытия.
  # Патологию нашёл коллега в гистограмме глубин своих фактов; я застал её у себя живьём —
  # 87 запущенных ветвей, из них решают две, load average 3.9 на 32 ядрах.
  # ЗАМЕРЕНО МНОЙ на живых кусках этой машины: d=0.4167/0.4667/0.6000/0.6667 закрываются за
  # 0.33 с каждый, все rc=20. Калибровка 0.35/0.38 снималась на малой глубине, где кусок велик
  # и решать его дорого; на глубине 34-46 эта посылка ложна, и правило работало наоборот.
  CEIL=${CEIL:-0.4286}
  if python3 -c "import sys; d=float('$DENS'); sys.exit(0 if d>=float('$SOS_DENS') and d<=float('$CEIL') else 1)" 2>/dev/null; then
    echo "ПЛОТНО $b (d=$DENS в ($SOS_DENS, $CEIL]) — дроблю без запуска решателя"
    rc=99
  fi
fi
if [ -z "$rc" ]; then
  timeout "$lim" kissat -q "$f" >/dev/null 2>&1; rc=$?
fi
case $rc in
  20) echo "$b" >> "$facts"; echo "ЗАКРЫТ $b"; exit 0 ;;
  10) echo "ВЫПОЛНИМ $b — УТВЕРЖДЕНИЕ РУШИТСЯ"; cp "$f" "$W/SAT_$b.cnf"; exit 9 ;;
  1)  echo "ОТКАЗ $b: решатель не разобрал файл (rc=1) — кусок НЕ решён"; exit 2 ;;
esac

if [ "$ci" -ge "$maxd" ] || [ "$ci" -ge "${#SCHED[@]}" ]; then
  echo "ПРЕДЕЛ $b (расписание исчерпано на шаге $ci)"; exit 1
fi
col=${SCHED[$ci]}
# ЗАЩИТА ДИСКА. Дробление держит по 42-64 файла на КАЖДОМ уровне вложенности; при семи
# работниках и глубине семь это гигабайты. Переполнение диска даёт ОБОРВАННЫЕ файлы, а
# оборванный файл решатель возвращает как rc=1 — и в журнале эта строка неотличима от
# результата. Именно так мы потеряли 280 фактов. Лучше отказать, чем испортить.
mkdir -p "$W"      # без этого df мерит несуществующий путь и молча возвращает пустоту
FREEMB=$(df -m "$W" 2>/dev/null | tail -1 | awk '{print $4}')
case "$FREEMB" in
  ''|*[!0-9]*)
    # ИЗМЕРИТЬ НЕ УДАЛОСЬ — это НЕ то же самое, что «места нет». Ворота, отказавшие из-за
    # собственной неспособности измерить, дают ЛОЖНУЮ ТРЕВОГУ: так у меня встал целый прогон
    # при 4.5 ГБ свободных, потому что переменная каталога не доехала до дочернего запуска.
    echo "ОТКАЗ $b: не удалось измерить свободное место на «$W» — это отказ ИЗМЕРЕНИЯ, не диска"
    exit 4 ;;
esac
# ПОРОГ ИЗМЕРЕН, а не назначен: одно дробление на 64 ребёнка даёт 3.5 ГБ (замер 2026-08-21,
# 630 МБ/с, то есть скорость диска). Прежний порог 2000 МБ проходил проверку и НЕ ХВАТАЛ —
# разбиение обрывалось на 31 ребёнке из 64, и ворота ловили это уже ПОСЛЕ порчи.
# Ворота, меряющие верную величину неверным порогом, бесполезны так же, как не меряющие вовсе.
NEED=${SOS_NEED_MB:-4500}
if [ "$FREEMB" -lt "$NEED" ]; then
  echo "ОТКАЗ $b: на диске ${FREEMB}МБ при потребности ${NEED} (одно дробление = 3.5 ГБ). Работа НЕ потеряна."
  exit 3
fi
d="$W/sos/$b"; rm -rf "$d"; mkdir -p "$d"
python3 "$R/subsplit.py" "$f" "$NN" "$col" 3 "$d" >/dev/null 2>&1
k=$(ls "$d"/*.cnf 2>/dev/null | wc -l)
EXP=$(python3 -c "from math import comb;print(sum(comb($NN,k) for k in range(4)))")
if [ "$k" -ne "$EXP" ]; then echo "ОТКАЗ $b: детей $k вместо $EXP — разбиение неполно"; rm -rf "$d"; exit 2; fi
echo "ДРОБЛЮ $b столбцом $col"
bad=0
for g in $(ls -r "$d"/*.cnf); do
  "$0" "$g" $((ci+1)) "$lim" "$maxd" "$facts" "$NN" || bad=1
  rm -f "$g"
done
rm -rf "$d"
[ "$bad" -eq 0 ] || exit 1
